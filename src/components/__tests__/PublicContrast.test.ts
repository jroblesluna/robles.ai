import { expect, it } from 'vitest';
import colors from 'tailwindcss/colors';
import config from '../../../tailwind.config';
import en from '../../i18n/locales/en/translation.json';
import es from '../../i18n/locales/es/translation.json';

function luminance(hex: string) {
  const rgb = hex.slice(1).match(/../g)!.map(value => parseInt(value, 16) / 255);
  const linear = rgb.map(value => value <= 0.04045 ? value / 12.92 : ((value + 0.055) / 1.055) ** 2.4);
  return linear[0] * 0.2126 + linear[1] * 0.7152 + linear[2] * 0.0722;
}
function whiteContrast(className: string) {
  const match = /(?:hover:)?(?:bg|text)-([a-z]+)-(\d+)/.exec(className);
  if (!match) throw new Error(`Unsupported configured color: ${className}`);
  const hex = (colors as unknown as Record<string, Record<string, string>>)[match[1]][match[2]];
  return 1.05 / (luminance(hex) + 0.05);
}
it.each([['en', en], ['es', es]] as const)('keeps %s configured course controls and team labels readable and generated by Tailwind', (_lang, locale) => {
  for (const course of locale.courses.items) {
    for (const color of [course.buttonBg, course.buttonHoverBg]) {
      expect(whiteContrast(color), `${course.title}: ${color}`).toBeGreaterThanOrEqual(4.5);
      expect(config.safelist).toContain(color);
    }
  }
  for (const member of locale.team.members) {
    expect(whiteContrast(member.positionColor), member.name).toBeGreaterThanOrEqual(4.5);
    expect(config.safelist).toContain(member.positionColor);
  }
});
